def corrected_cramers_v(table):
    n = table.sum()
    r,c = table.shape
    if min(r,c)<2: return 0.0
    chi = chi2_contingency(table, correction=False)[0]
    phi = max(0,chi/n-(c-1)*(r-1)/(n-1))
    rc = r-(r-1)**2/(n-1)
    cc = c-(c-1)**2/(n-1)
    denom = min(rc-1,cc-1)
    return float(np.sqrt(phi/denom)) if denom>0 else 0.0

def bh_adjust(pvalues):
    p = np.asarray(pvalues,dtype=float)
    order = np.argsort(p)
    adj = np.minimum.accumulate((p[order]*len(p)/np.arange(1,len(p)+1))[::-1])[::-1]
    result = np.empty_like(adj)
    result[order] = np.minimum(adj,1)
    return result

