def explain_new_farmers(input_csv_path,output_prefix='new_farmers'):
    """Analyze newly supplied farmers without inventing their true yield."""
    new=pd.read_csv(input_csv_path,keep_default_na=False,dtype=str)
    missing=set(FEATURES)-set(new.columns)
    if missing:raise ValueError('Missing predictors: '+', '.join(sorted(missing)))
